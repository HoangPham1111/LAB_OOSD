-- Xem thông tin nhân viên kinh doanh
SELECT nv.MA_NV, nv.TEN_NV, nv.DIA_CHI
FROM NHAN_VIEN nv
INNER JOIN NV_KINH_DOANH nvkd ON nv.MA_NV = nvkd.MA_NV;

-- Xem nhân viên tập sự và người hướng dẫn
SELECT 
    ts.MA_NV AS Ma_TapSu, 
    nv_ts.TEN_NV AS Ten_TapSu,
    ts.MA_NV_HUONG_DAN AS Ma_HuongDan,
    nv_hd.TEN_NV AS Ten_HuongDan
FROM NV_KD_TAP_SU ts
JOIN NHAN_VIEN nv_ts ON ts.MA_NV = nv_ts.MA_NV
LEFT JOIN NHAN_VIEN nv_hd ON ts.MA_NV_HUONG_DAN = nv_hd.MA_NV;

-- Xem tổng hoa hồng theo từng đơn hàng (Đã sửa lỗi bảng NHAN_VIEN)
SELECT dh.SO_DOH, dh.KHACH_HANG, nv.TEN_NV, tl.HOA_HONG
FROM DON_HANG dh
JOIN THUONG_LUONG tl ON dh.SO_DOH = tl.SO_DOH
JOIN NHAN_VIEN nv ON tl.MA_NV = nv.MA_NV;