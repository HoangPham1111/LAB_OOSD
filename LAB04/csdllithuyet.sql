CREATE TABLE NHAN_VIEN (
    MA_NV VARCHAR(20) PRIMARY KEY,
    TEN_NV NVARCHAR(100) NOT NULL,
    DIA_CHI NVARCHAR(200)
);
CREATE TABLE QUA_TRINH_TANG_LUONG (
    MA_NV VARCHAR(20) NOT NULL,
    NGAY_HIEU_LUC DATE NOT NULL,
    LUONG_MOI DECIMAL(18, 2) NOT NULL,
    PRIMARY KEY (MA_NV, NGAY_HIEU_LUC),
    FOREIGN KEY (MA_NV) REFERENCES NHAN_VIEN(MA_NV) ON DELETE CASCADE
);
CREATE TABLE NV_KINH_DOANH (
    MA_NV VARCHAR(20) PRIMARY KEY,
    FOREIGN KEY (MA_NV) REFERENCES NHAN_VIEN(MA_NV) ON DELETE CASCADE
);
CREATE TABLE NV_KD_LAU_NAM (
    MA_NV VARCHAR(20) PRIMARY KEY,
    FOREIGN KEY (MA_NV) REFERENCES NV_KINH_DOANH(MA_NV) ON DELETE CASCADE
);
CREATE TABLE NV_KD_TAP_SU (
    MA_NV VARCHAR(20) PRIMARY KEY,
    MA_NV_HUONG_DAN VARCHAR(20) NULL,
    FOREIGN KEY (MA_NV) REFERENCES NV_KINH_DOANH(MA_NV) ON DELETE CASCADE,
    FOREIGN KEY (MA_NV_HUONG_DAN) REFERENCES NV_KD_LAU_NAM(MA_NV) ON DELETE NO ACTION
);
CREATE TABLE DON_HANG (
    SO_DOH VARCHAR(20) PRIMARY KEY,
    KHACH_HANG NVARCHAR(100) NOT NULL,
    TRI_GIA DECIMAL(18, 2) NOT NULL DEFAULT 0
);
CREATE TABLE THUONG_LUONG (
    MA_NV VARCHAR(20) NOT NULL,
    SO_DOH VARCHAR(20) NOT NULL,
    HOA_HONG DECIMAL(18, 2) NOT NULL DEFAULT 0,
    PRIMARY KEY (MA_NV, SO_DOH),
    FOREIGN KEY (MA_NV) REFERENCES NV_KINH_DOANH(MA_NV) ON DELETE CASCADE,
    FOREIGN KEY (SO_DOH) REFERENCES DON_HANG(SO_DOH) ON DELETE CASCADE
);
